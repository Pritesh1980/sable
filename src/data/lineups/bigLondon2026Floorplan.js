// Where each stand physically sits at the Big London Tattoo Show 2026, taken
// from the show's own published floorplan (the PDF linked from
// /floorplan-and-artist-trader-list — one page, a single 6400x4233 image).
//
// Positions are `[x, y]` normalised 0–1 against that image, origin top-left, so
// they survive any re-render of the plan at a different size. The show's
// floorplan artwork itself is deliberately NOT in this repo — these are just the
// coordinates read off it.
//
// Why this exists: the booth numbering serpentines. On the right-hand island
// 209–220 runs along the top face and 208–197 back along the bottom, so sorting
// a route by booth number walks one side of an aisle and then jumps across it.
// Ordering by real position is the only way to get a sane walk.
//
// Extraction (reproducible — see docs/plans/convention-route-planner.md):
// colour-mask the booth rectangles, then OCR each cell, thresholding dark pixels
// directly rather than with Otsu, which silently eats digits ("276" reads as
// "28"). 391 booths were read that way; 8 more were placed by
// interpolating between their numbered neighbours and checking the midpoint
// lands inside a real rectangle.
//
// KNOWN GAPS — consumers must degrade gracefully, never guess a position:
//   - 54 booths on the artist list are not drawn on this plan at all: the whole
//     521–556 block, T1–T43 and P2–P4. The highest booth drawn is 520.
//   - The plan skips 122, 233 and 322 entirely (the rows run …123, 121, 120…,
//     …232, 234…, …323, 321…), yet artists are listed at all three.
//   - Booth 94 is drawn, but its artist (Lucy Thompson, listed at both 94 and
//     340) dedupes to 340, so nothing in the app sits there.
//   - 8 further booths could not be read: 78, 91, 117, 171, 261, 348, 375, 457.
